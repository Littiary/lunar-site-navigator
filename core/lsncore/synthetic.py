def synthetic_positions_km(et_s: np.ndarray) -> np.ndarray:
    """Invented Sun and Earth positions in the body-fixed frame, shape [N, 2, 3]."""
    t = np.asarray(et_s, dtype=np.float64)
    sun_lon = -2.0 * np.pi * t / _SUN_PERIOD_S
    sun_lat = 1.5 * DEG * np.sin(2.0 * np.pi * t / (12.0 * _SUN_PERIOD_S))
    earth_lon = 6.0 * DEG * np.sin(2.0 * np.pi * t / _EARTH_WOBBLE_PERIOD_S)
    earth_lat = 6.0 * DEG * np.cos(2.0 * np.pi * t / _EARTH_WOBBLE_PERIOD_S)

    def vec(lat, lon, dist):
        return dist * np.stack([np.cos(lat) * np.cos(lon), np.cos(lat) * np.sin(lon), np.sin(lat)], axis=-1)

    return np.stack(
        [vec(sun_lat, sun_lon, _SUN_DISTANCE_KM), vec(earth_lat, earth_lon, _EARTH_DISTANCE_KM)], axis=1
    )


