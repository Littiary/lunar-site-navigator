class SyntheticClock:
    """UTC <-> ET for synthetic packages: ET is counted from 2000-01-01T12:00:00 UTC.

    This ignores the offset between TDB and UTC on purpose (no kernels are involved).
    Real packages take both conversions from SPICE.
    """

    @staticmethod
    def utc_to_et(utc: str) -> float:
        when = _dt.datetime.strptime(utc, "%Y-%m-%dT%H:%M:%S.%fZ").replace(tzinfo=_dt.timezone.utc)
        return (when - _J2000).total_seconds()

    @staticmethod
    def et_to_utc(et_s: float) -> str:
        return format_utc(_J2000 + _dt.timedelta(seconds=round(float(et_s), 3)))


def _tri(x):
    """Triangle wave with period 1: 0 at integers, 1 at half-integers."""
    return np.abs(2.0 * (x - np.floor(x + 0.5)))


